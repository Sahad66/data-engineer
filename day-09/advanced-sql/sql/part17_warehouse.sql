-- E-commerce Sales Data Warehouse

CREATE SCHEMA IF NOT EXISTS ecommerce_dw;

CREATE TABLE IF NOT EXISTS ecommerce_dw.dim_product (
    product_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id VARCHAR(30) UNIQUE NOT NULL,
    product_name VARCHAR(100) NOT NULL,
    category VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS ecommerce_dw.dim_customer (
    customer_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(30) UNIQUE NOT NULL,
    customer_name VARCHAR(100) NOT NULL,
    city VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS ecommerce_dw.dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE UNIQUE NOT NULL,
    year INTEGER NOT NULL,
    month INTEGER NOT NULL,
    month_name VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS ecommerce_dw.fact_sales (
    sale_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_order_id INTEGER NOT NULL,
    product_key INTEGER NOT NULL
        REFERENCES ecommerce_dw.dim_product(product_key),
    customer_key INTEGER NOT NULL
        REFERENCES ecommerce_dw.dim_customer(customer_key),
    date_key INTEGER NOT NULL
        REFERENCES ecommerce_dw.dim_date(date_key),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    sales_amount NUMERIC(14,2) NOT NULL CHECK (sales_amount >= 0),
    UNIQUE (source_order_id, product_key)
);